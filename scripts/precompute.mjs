// Precomputes the service scenarios and the optimizer's ranked plans that the site shows without running them live.
//   npm run precompute            writes src/sim/precomputed.data.js
// Re-run it after changing /data or the simulation; `npm test` fails while the file is stale.
import { readFile, writeFile } from 'node:fs/promises';
import { loadKitchenData } from '../src/sim/data/load.js';
import { createSim } from '../src/sim/sim.js';
import { optimize, summarize } from '../src/sim/optimize.js';
import { runHeadless } from '../src/sim/scenarios.js';
import { fingerprint, configKey } from '../src/sim/precomputed.js';

export const GUESTS = [40, 62, 90, 120];

const data = await loadKitchenData((n) => readFile(new URL(`../data/${n}.json`, import.meta.url), 'utf8').then(JSON.parse));
const round = (v) => (typeof v === 'number' ? Math.round(v * 1000) / 1000 : Array.isArray(v) ? v.map(round)
  : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, round(x)])) : v);

const forecasts = {}; const scenarios = [];
for (const covers of GUESTS) {
  const cfg = createSim({ data, covers }).config;
  const t0 = Date.now();
  const opt = await optimize(data, cfg, { yieldEvery: 1e9 });
  const remember = (patch) => { const s = runHeadless(data, { ...cfg, ...patch }); forecasts[configKey({ ...cfg, ...patch })] = s.endT; return summarize(s); };
  const base = remember({});
  const candidates = opt.candidates.map((c) => ({
    id: c.id, kind: c.kind, label: c.label, detail: c.detail, patch: c.patch, ok: c.ok, flags: c.flags,
    saved: c.saved, meetsTarget: c.meetsTarget, mean: c.mean, seed1: c.runs[0],
  }));
  // every plan replays instantly on the live twin: its night's end is cached too
  const keep = candidates.map((c) => c.id);
  for (const c of candidates) remember(c.patch);
  scenarios.push({ ...round({
    id: `guests-${covers}`, covers, seating: cfg.seating, seed: cfg.seed, isDefault: covers === data.sim?.defaultCovers,
    base, target: opt.target, baselineMean: opt.baseline.mean, recommended: opt.recommended, replayable: keep, candidates,
  }), config: cfg }); // the exact resolved config (unrounded), so a loaded night matches its cached run
  console.log(`${covers} guests: meal ${(base.mealAvg / 60).toFixed(1)} min (target ${(opt.target / 60).toFixed(0)}), recommended ${opt.recommended} (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
}

const lib = { fingerprint: fingerprint(data), seeds: [1, 2, 3, 4, 5], scenarios, forecasts };
await writeFile(new URL('../src/sim/precomputed.data.js', import.meta.url),
  `// Generated by scripts/precompute.mjs (npm run precompute). Do not edit by hand.\nexport default ${JSON.stringify(lib)};\n`);
console.log('wrote src/sim/precomputed.data.js');
